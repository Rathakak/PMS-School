// Build a complete 10-Slide Exercise Deck for Grade 5 (either Daily Mix or Lesson-specific, with optional day seed)
export function getGrade5TenSlideDeck(lessonId: number, daySeed: number = 0): MathSlideExercise[] {
  const allG5 = [...GRADE_5_EXERCISE_POOL, ...GRADE_5_EXTRA_POOL];

  if (lessonId === 0) {
    // Rotate or select 10 slides based on daySeed so every day has a fresh 10-slide sequence!
    const rotated = [...allG5];
    const offset = (daySeed * 3) % rotated.length;
    const picked = [...rotated.slice(offset), ...rotated.slice(0, offset)].slice(0, 10);
    return picked.map((item, idx) => ({
      ...item,
      id: `g5-daily-${daySeed}-s${idx + 1}`,
      slideNumber: idx + 1,
    }));
  }

  const lesson = GRADE_5_LESSONS.find((l) => l.id === lessonId) || GRADE_5_LESSONS[0];
  const matching = allG5.filter((s) => s.lessonId === lessonId);
  const others = allG5.filter((s) => s.lessonId !== lessonId);
  const offset = (daySeed * 2) % Math.max(1, others.length);
  const rotatedOthers = [...others.slice(offset), ...others.slice(0, offset)];

  const combined = [...matching, ...rotatedOthers].slice(0, 10);
  return combined.map((item, idx) => ({
    ...item,
    id: `g5-lesson-${lessonId}-d${daySeed}-s${idx + 1}`,
    slideNumber: idx + 1,
    categoryLabel:
      idx < matching.length
        ? `លំហាត់គោល · ${lesson.title}`
        : `លំហាត់រំលឹកប្រចាំថ្ងៃ · ${item.lessonTitle}`,
  }));
}
