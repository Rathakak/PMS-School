export function buildLesson10Slides(lessonId: number, baseSlides: MathSlideExercise[]): MathSlideExercise[] {
  if (lessonId === 0) return baseSlides;
  const lesson = GRADE_6_LESSONS.find((l) => l.id === lessonId) || GRADE_6_LESSONS[0];

  // Combine matching lesson exercises first, then related exercises so every lesson pack has 10 complete slides
  const matching = [...baseSlides, ...TEXTBOOK_EXERCISE_POOL].filter((s) => s.lessonId === lessonId);
  const others = [...TEXTBOOK_EXERCISE_POOL, ...baseSlides].filter((s) => s.lessonId !== lessonId);
  const combined = [...matching, ...others].slice(0, 10);

  return combined.map((item, idx) => ({
    ...item,
    id: `pack-${lessonId}-slide-${idx + 1}`,
    slideNumber: idx + 1,
    categoryLabel: idx < matching.length ? `លំហាត់គោល · ${lesson.title}` : `លំហាត់រំលឹកបន្ថែម · ${item.lessonTitle}`,
  }));
}
